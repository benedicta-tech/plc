class DailyReading {
  final DateTime date;
  final String title;
  final String color;
  final String details;
  final String readings;
  final String body;

  DailyReading({
    required this.date,
    required this.title,
    required this.color,
    required this.details,
    required this.readings,
    required this.body,
  });
}
